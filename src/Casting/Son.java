package Casting;

public class Son extends Father  //inheritance
{
    public void mobile()
    {
        System.out.println("Iphone18");
    }
    public void car()
    {
        System.out.println("BMW");   //method overriding
    }
    public void money()
    {
        System.out.println("Three lakh");   //method overriding
    }
    public void home()
    {
        System.out.println("5BHK");
    }
}
